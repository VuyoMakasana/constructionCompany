import 'dotenv/config';
import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import rateLimit from 'express-rate-limit';
import { router } from './routes.js';
import { emailConfigured } from './mailer.js';
import { db } from './db.js';
const app = express();
app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json({ limit: '50kb' }));
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please try again later.' } }));
app.get('/api/health', (_q, r) => r.json({ ok: true, email: emailConfigured(), database: Boolean(db) }));
app.use('/api', router);
app.use('/api', (_q, r) => r.status(404).json({ error: 'Not found' }));
app.use((err, _q, res, _n) => { console.error(err); res.status(err.type === 'entity.parse.failed' ? 400 : 500).json({ error: 'Something went wrong. Please try again.' }); });
export default app;
